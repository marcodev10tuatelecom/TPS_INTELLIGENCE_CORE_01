  SELECT 'AUDIENCE_SEGMENT','Audience Segment' FROM dual UNION ALL
  SELECT 'CONTRACT','Contract' FROM dual UNION ALL
  SELECT 'RIGHT','Right' FROM dual UNION ALL
  SELECT 'LOCATION','Location' FROM dual UNION ALL
  SELECT 'REGION','Region' FROM dual UNION ALL
  SELECT 'EVENT','Event' FROM dual UNION ALL
  SELECT 'DEVICE','Device' FROM dual UNION ALL
  SELECT 'SERVICE','Service' FROM dual UNION ALL
  SELECT 'SYSTEM','System' FROM dual UNION ALL
