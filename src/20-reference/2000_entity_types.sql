  SELECT 'BRAND','Brand' FROM dual UNION ALL
  SELECT 'RADIO_STATION','Radio Station' FROM dual UNION ALL
  SELECT 'TV_STATION','TV Station' FROM dual UNION ALL
  SELECT 'AFFILIATE','Affiliate' FROM dual UNION ALL
  SELECT 'REPEATER','Repeater' FROM dual UNION ALL
  SELECT 'CHANNEL','Channel' FROM dual UNION ALL
  SELECT 'PROGRAM','Program' FROM dual UNION ALL
  SELECT 'SONG','Song' FROM dual UNION ALL
  SELECT 'RECORDING','Recording' FROM dual UNION ALL
  SELECT 'ALBUM','Album' FROM dual UNION ALL
  SELECT 'AUDIO','Audio' FROM dual UNION ALL
  SELECT 'VIDEO','Video' FROM dual UNION ALL
  SELECT 'IMAGE','Image' FROM dual UNION ALL
  SELECT 'PODCAST','Podcast' FROM dual UNION ALL
  SELECT 'EPISODE','Episode' FROM dual UNION ALL
  SELECT 'NEWS_ARTICLE','News Article' FROM dual UNION ALL
  SELECT 'REPORT','Report' FROM dual UNION ALL
  SELECT 'INTERVIEW','Interview' FROM dual UNION ALL
  SELECT 'COMMERCIAL','Commercial' FROM dual UNION ALL
